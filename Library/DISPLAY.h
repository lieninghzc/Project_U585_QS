#ifndef __DISPLAY_H
#define __DISPLAY_H

/**
  * @brief  OLED 显示管理模块
  *
  *  功能:
  *    1. 统一封装 OLED 所有显示内容, 主循环只需调 DISPLAY_Update()
  *    2. 内部维护阴影缓冲, 仅当内容变化时才刷新对应字符到 OLED,
  *       消除闪烁并减少 I2C 通信量
  *    3. 移除主循环中的 OLED_Clear(), 避免每帧全屏重绘
  *
  *  屏幕布局 (4 行 x 16 字符):
  *    ┌──────────────────────────────────┐
  *    │ T:+25.39C S:25.5H                │  行1: 温度 / 设定 / 加热指示
  *    │ H:44.23% WS:60W                  │  行2: 湿度 / 设定 / 加湿指示
  *    │ L:12345lx                        │  行3: 光照度
  *    │ ENC:+12345678                    │  行4: 编码器增量
  *    └──────────────────────────────────┘
  */

#include <stdint.h>

/* ======================== 初始化 ======================== */

/**
  * @brief  初始化 OLED, 显示启动画面, 清空阴影缓冲
  */
void DISPLAY_Init(void);

/* ======================== 主刷新入口 ======================== */

/**
  * @brief  刷新所有显示行 (在主循环中周期性调用)
  *
  *         内部流程:
  *           1. 读取各传感器最新数值
  *           2. 格式化每行字符串 (16 字符)
  *           3. 逐字符对比阴影缓冲, 仅将变化位置写入 OLED
  *
  * @note   调用前需确保 SENS_Read() 已执行
  */
void DISPLAY_Update(void);

/* ======================== 单行强制刷新 ======================== */

/**
  * @brief  强制刷新指定行到 OLED (无视阴影缓存)
  * @param  line  行号 1~4
  */
void DISPLAY_FlushLine(uint8_t line);

#endif /* __DISPLAY_H */
